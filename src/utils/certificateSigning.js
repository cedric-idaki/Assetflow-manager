/**
 * One line about where a signing request has got to, and the tone to say it in.
 *
 * `released` is the only state in which the document is the issued certificate.
 * Everything else — including `signed` — is deliberately NOT presented as
 * issued, because a tenant that turned auto-release off has chosen to have a
 * person look at it first.
 */
export const SIGNING_VERDICTS = {
  draft: { tone: 'muted', label: 'Not sent', detail: 'Generated, but nobody has been asked to sign it yet.' },
  sent: { tone: 'pending', label: 'Out for signature', detail: 'Waiting on the signatories.' },
  viewed: { tone: 'pending', label: 'Opened', detail: 'A signatory has opened it but not signed.' },
  signed: { tone: 'success', label: 'Signed', detail: 'Every signatory has signed. Awaiting release.' },
  released: { tone: 'success', label: 'Issued', detail: 'Signed by every signatory and issued as the certificate of record.' },
  declined: { tone: 'danger', label: 'Declined', detail: 'A signatory refused to sign.' },
  cancelled: { tone: 'muted', label: 'Withdrawn', detail: 'The request was withdrawn before it was signed.' },
  expired: { tone: 'warning', label: 'Expired', detail: 'The invite lapsed before everyone signed.' },
  failed: { tone: 'danger', label: 'Failed to send', detail: 'The document never reached SignNow.' },
};

/**
 * Where the certificate vocabulary is simply the wrong word.
 *
 * A guarantee agreement is not "issued" — nobody issues an undertaking to
 * themselves. It is EXECUTED, and the distinction is the whole point of routing
 * it through SignNow: an issued certificate is a claim the society makes, an
 * executed agreement is one the guarantor made. Only the states where the two
 * vocabularies actually differ are overridden.
 */
const KIND_VERDICTS = {
  guarantee_agreement: {
    signed: {
      tone: 'success',
      label: 'Signed',
      detail: 'Every party has signed. Awaiting release as the executed agreement.',
    },
    released: {
      tone: 'success',
      label: 'Executed',
      detail: 'Signed by every party and stored as the executed agreement of record.',
    },
    failed: { tone: 'danger', label: 'Failed to send', detail: 'The agreement never reached SignNow.' },
  },
};

export const signingVerdict = (status, docKind) =>
  KIND_VERDICTS[docKind]?.[status]
  || SIGNING_VERDICTS[status]
  || { tone: 'muted', label: 'Unknown', detail: '' };

/** Terminal states: nothing more will happen without somebody starting again. */
export const isTerminal = (status) =>
  ['released', 'declined', 'cancelled', 'expired', 'failed'].includes(status);

/** Is this document releasable as the certificate of record? */
export const isIssued = (status) => status === 'released';

/**
 * Whether a certificate may be handed out.
 *
 * Three-way on purpose, because "no" has two very different reasons and the
 * screen has to say which:
 *   allowed  — hand it over
 *   draft    — signing is not required here, so an unsigned copy is the norm
 *   blocked  — signing IS required and has not completed
 */
export const releaseState = (requireSignature, request) => {
  if (isIssued(request?.status)) return { kind: 'allowed', signed: true };
  if (!requireSignature) return { kind: 'draft', signed: false };
  return {
    kind: 'blocked',
    signed: false,
    reason: request
      ? signingVerdict(request.status).detail
      : 'This certificate has to be signed before it can be issued.',
  };
};

/** A signer entry the RPC will accept, or null when it is not usable. */
export const cleanSigner = (s, index) => {
  const email = String(s?.email || '').trim().toLowerCase();
  const role = String(s?.role || '').trim();
  if (!email || !role) return null;
  if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email)) return null;
  return {
    role,
    name: String(s?.name || '').trim() || null,
    email,
    order: Number(s?.order) || index + 1,
  };
};

export const cleanPanel = (list) =>
  (Array.isArray(list) ? list : []).map(cleanSigner).filter(Boolean);
