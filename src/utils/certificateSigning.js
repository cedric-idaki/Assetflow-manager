// ── Page geometry ───────────────────────────────────────────────────────────
export const A4 = {
  portrait: { width: 595.28, height: 841.89 },
  landscape: { width: 841.89, height: 595.28 },
};

/** How tall a signature block is, and how much room its ruled line needs. */
export const SIG_BLOCK = { width: 150, height: 40, dateHeight: 14, gap: 28 };

/** Side margin the signature row is laid out within. */
const SIG_MARGIN = 40;

/**
 * Lay `count` signature blocks across the foot of a page.
 *
 * Returns the top-left corner of each signing box plus the y of the ruled line
 * that goes under it, so the generator can draw the line and the caption while
 * the signing box sits directly above — which is what a wet-ink signature does
 * on paper, and what a reader expects to see.
 *
 * `bottomOffset` is measured from the bottom of the page, because that is how
 * every certificate design in this codebase positions its signature row: a
 * fixed distance up from the foot, whatever is above it.
 *
 * A row that does not fit at the preferred width SHRINKS — both the gap and the
 * blocks themselves. Keeping the block width fixed and only tightening the gap
 * looks like it works for three officers and silently pushes the fourth off the
 * edge of the page, where SignNow would place a signing box nobody can reach.
 */
export const signatureBlocks = (count, { width, height }, bottomOffset = 120) => {
  const n = Math.max(1, count);
  const available = Math.max(1, width - SIG_MARGIN * 2);

  let gap = n > 1 ? SIG_BLOCK.gap : 0;
  let w = SIG_BLOCK.width;

  if (n * w + (n - 1) * gap > available) {
    // Give up the gap first — the space between blocks is decoration, the
    // block itself is the thing a signature has to land inside.
    gap = n > 1 ? Math.min(gap, available * 0.04) : 0;
    w = (available - (n - 1) * gap) / n;
  }

  const total = n * w + (n - 1) * gap;
  const startX = SIG_MARGIN + (available - total) / 2;
  const boxTop = height - bottomOffset - SIG_BLOCK.height;

  return Array.from({ length: n }, (_, i) => ({
    index: i,
    x: startX + i * (w + gap),
    y: boxTop,
    width: w,
    height: SIG_BLOCK.height,
    /** The ruled line the signature sits on. */
    lineY: boxTop + SIG_BLOCK.height + 2,
    /** Where the office caption goes, under the line. */
    captionY: boxTop + SIG_BLOCK.height + 14,
  }));
};

/**
 * The field list sent to signnow-documents, built from the same blocks the
 * generator drew. `role` is what ties a field to a signer row, so it must be
 * the signer's role_name exactly.
 */
export const fieldsForSigners = (signers, page, geometry, bottomOffset) => {
  const blocks = signatureBlocks(signers.length, geometry, bottomOffset);
  return signers.map((s, i) => ({
    role: s.role,
    page,
    x: blocks[i].x,
    y: blocks[i].y,
    width: blocks[i].width,
    height: blocks[i].height,
    withDate: true,
  }));
};

