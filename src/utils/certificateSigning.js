/**
 * CERTIFICATE SIGNING — the shared vocabulary.
 *
 * One module names the document kinds, the panels who sign them, and — the part
 * that matters most — WHERE the signature blocks sit on the page.
 *
 * WHY THE LAYOUT LIVES HERE
 * -------------------------
 * Two things have to agree about the position of every signature block: the
 * generator that draws the ruled line on the PDF, and the field placement that
 * tells SignNow where to put the signing box. If they disagree by 20 points the
 * signature lands next to the line instead of on it, and nobody notices until a
 * member is holding the paper. So neither of them owns the numbers — this does,
 * and both read from it.
 *
 * COORDINATES
 * -----------
 * PDF points, from the TOP-LEFT of the page. jsPDF (constructed with unit:'pt')
 * and SignNow both use that origin, so a number here is used unchanged by both.
 * pdf-lib does NOT — it measures from the bottom-left — so anything that later
 * stamps these positions with pdf-lib must flip y. See applySignatureToPDF.js,
 * which is a separate path and does its own thing.
 */

